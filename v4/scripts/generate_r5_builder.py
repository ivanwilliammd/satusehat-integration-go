#!/usr/bin/env python3
"""Hasilkan lapisan namespace R5 untuk builder Go dari builder kanon (R4).

Go tidak punya pewarisan kelas, jadi "menurunkan builder kanon" dilakukan lewat embedding:
struct R5 membenamkan pointer ke builder kanon, sehingga seluruh permukaan method kanon
terpromosikan tanpa ditulis ulang. Konsekuensinya memakai R5 cukup dengan mengganti import,
sama seperti port PHP/Node/Python.

Bila satu resource MEMANG berbeda di R5, berkas hasil generate untuk resource itu diganti dengan
implementasi tulisan tangan. Generator tidak akan menyentuhnya: berkas tanpa penanda
"Code generated by" dianggap milik manusia.

Jalankan: python3 scripts/generate_r5_builder.py [--check]
"""
import pathlib
import re
import sys

AKAR = pathlib.Path(__file__).resolve().parents[1]
SUMBER = AKAR / "src" / "builder"
TUJUAN = AKAR / "src" / "r5" / "builder"
MODUL = "github.com/ivanwilliammd/satusehat-integration-go/v4"
PENANDA = "// Code generated by scripts/generate_r5_builder.py; DO NOT EDIT."

POLA_STRUCT = re.compile(r"^type (\w+Builder) struct", re.M)
POLA_KONSTRUKTOR = re.compile(r"^func (New\w+Builder)\(([^)]*)\) \*(\w+Builder)", re.M)


def parameter(daftar_param: str) -> tuple[str, str]:
    """Kembalikan (deklarasi parameter, argumen penerusan) dari daftar parameter konstruktor."""
    if not daftar_param.strip():
        return "", ""
    deklarasi, argumen = [], []
    for bagian in daftar_param.split(","):
        bagian = bagian.strip()
        nama = bagian.split()[0]
        deklarasi.append(bagian)
        argumen.append(f"{nama}..." if "..." in bagian else nama)
    return ", ".join(deklarasi), ", ".join(argumen)


def pasangan() -> list[tuple[pathlib.Path, str, str, str, str]]:
    hasil = []
    for berkas in sorted(SUMBER.glob("*.go")):
        if berkas.name.endswith("_test.go"):
            continue
        teks = berkas.read_text()
        tipe = POLA_STRUCT.search(teks)
        if not tipe:
            continue
        nama = tipe.group(1)
        konstruktor = re.search(rf"^func (New{nama})\(([^)]*)\) \*{nama}\b", teks, re.M)
        if not konstruktor:
            raise SystemExit(f"{berkas.name}: tidak ada konstruktor New{nama}")
        deklarasi, argumen = parameter(konstruktor.group(2))
        hasil.append((berkas, nama, konstruktor.group(1), deklarasi, argumen))
    return hasil


def isi_berkas(nama: str, konstruktor: str, deklarasi: str, argumen: str) -> str:
    return f"""{PENANDA}
//
// Lapisan R5: turunan apa adanya dari builder kanon (R4) lewat embedding, karena Go tidak punya
// pewarisan kelas. Selama R5 tidak mengubah elemen resource ini, memakai R5 cukup dengan mengganti
// import. Bila R5 memang berbeda, hapus penanda "Code generated" dan tulis implementasinya di
// sini — generator akan berhenti menyentuh berkas ini.

package builder

import canon "{MODUL}/src/builder"

// {nama} adalah padanan R5 dari canon.{nama}. Seluruh method kanon terpromosikan tanpa perubahan,
// jadi pemanggil cukup mengganti import.
type {nama} struct {{
	*canon.{nama}
}}

// {konstruktor} membuat builder R5 yang dibacking builder kanon R4.
func {konstruktor}({deklarasi}) *{nama} {{
	return &{nama}{{{nama}: canon.{konstruktor}({argumen})}}
}}
"""


def isi_test(daftar: list[tuple[pathlib.Path, str, str, str, str]]) -> str:
    baris = "\n".join(
        f'\t\t{{"{nama}", {konstruktor}(), canon.{konstruktor}()}},' for _, nama, konstruktor, _, _ in daftar
    )
    return f'''{PENANDA}
//
// Uji permukaan method: setiap builder R5 harus mempromosikan method kanon secara utuh dan
// menghasilkan payload yang sama persis. Kalau satu method kanon hilang atau tertimpa, uji ini
// merah — bukan sekadar cocok karena tipe R5 adalah alias.

package builder

import (
	"encoding/json"
	"fmt"
	"reflect"
	"strings"
	"testing"

	canon "{MODUL}/src/builder"
)

type pasanganR5 struct {{
	nama  string
	r5    any
	kanon any
}}

func daftarPasangan() []pasanganR5 {{
	return []pasanganR5{{
{baris}
	}}
}}

func tandaMethod(t reflect.Type) []reflect.Type {{
	// Receiver (In(0)) dibuang: pada method yang terpromosikan, Go membungkusnya sehingga
	// In(0) menjadi tipe R5 sementara method kanon memakai tipe kanon. Sisanya harus identik.
	tanda := make([]reflect.Type, 0, t.NumIn()+t.NumOut())
	for i := 1; i < t.NumIn(); i++ {{
		tanda = append(tanda, t.In(i))
	}}
	for i := 0; i < t.NumOut(); i++ {{
		tanda = append(tanda, t.Out(i))
	}}
	return tanda
}}

// jelaskan menuliskan tipe beserta paket asalnya: dua tipe bisa bernama sama persis
// (builder.AccountBuilder) tetapi berasal dari paket berbeda, dan itulah yang dibandingkan.
func pkgPath(t reflect.Type) string {{
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {{
		t = t.Elem()
	}}
	return t.PkgPath()
}}

func jelaskan(tanda []reflect.Type) string {{
	bagian := make([]string, len(tanda))
	for i, t := range tanda {{
		bagian[i] = fmt.Sprintf("%s (%s)", t, pkgPath(t))
	}}
	return "[" + strings.Join(bagian, " ") + "]"
}}

func permukaanMethod(v any) map[string][]reflect.Type {{
	t := reflect.TypeOf(v)
	hasil := make(map[string][]reflect.Type, t.NumMethod())
	for i := 0; i < t.NumMethod(); i++ {{
		m := t.Method(i)
		hasil[m.Name] = tandaMethod(m.Type)
	}}
	return hasil
}}

func TestPermukaanMethodSamaDenganKanon(t *testing.T) {{
	pasangan := daftarPasangan()
	if len(pasangan) == 0 {{
		t.Fatal("tidak ada builder R5")
	}}
	for _, p := range pasangan {{
		kanon := permukaanMethod(p.kanon)
		r5 := permukaanMethod(p.r5)
		if len(kanon) == 0 {{
			t.Errorf("%s: kanon tidak punya method", p.nama)
			continue
		}}
		for nama, tanda := range kanon {{
			tandaR5, ada := r5[nama]
			if !ada {{
				t.Errorf("%s: method %s hilang di R5", p.nama, nama)
				continue
			}}
			if len(tandaR5) != len(tanda) {{
				t.Errorf("%s: method %s berubah tanda tangan\\n kanon: %s\\n   r5: %s", p.nama, nama, jelaskan(tanda), jelaskan(tandaR5))
				continue
			}}
			for i := range tanda {{
				if tandaR5[i] != tanda[i] {{
					t.Errorf("%s: method %s berubah tanda tangan\\n kanon: %s\\n   r5: %s", p.nama, nama, jelaskan(tanda), jelaskan(tandaR5))
					break
				}}
			}}
		}}
		if len(r5) != len(kanon) {{
			t.Errorf("%s: jumlah method R5 %d, kanon %d", p.nama, len(r5), len(kanon))
		}}
	}}
}}

func TestTipeR5BernamaSamaDenganKanon(t *testing.T) {{
	for _, p := range daftarPasangan() {{
		namaKanon := reflect.TypeOf(p.kanon).Elem().Name()
		namaR5 := reflect.TypeOf(p.r5).Elem().Name()
		if namaR5 != namaKanon {{
			t.Errorf("%s: tipe R5 bernama %s, kanon %s", p.nama, namaR5, namaKanon)
		}}
	}}
}}

func TestBuildR5SamaDenganKanon(t *testing.T) {{
	for _, p := range daftarPasangan() {{
		buildKanon := p.kanon.(interface{{ Build() map[string]interface{{}} }}).Build()
		buildR5 := p.r5.(interface{{ Build() map[string]interface{{}} }}).Build()
		jsonKanon, err := json.Marshal(buildKanon)
		if err != nil {{
			t.Fatalf("%s: kanon tidak bisa di-marshal: %v", p.nama, err)
		}}
		jsonR5, err := json.Marshal(buildR5)
		if err != nil {{
			t.Fatalf("%s: R5 tidak bisa di-marshal: %v", p.nama, err)
		}}
		if string(jsonKanon) != string(jsonR5) {{
			t.Errorf("%s: payload beda\\n kanon: {{jsonKanon}}\\n   r5: {{jsonR5}}", p.nama)
			continue
		}}
		if build, ok := buildR5["resourceType"].(string); !ok || build == "" {{
			t.Errorf("%s: resourceType kosong", p.nama)
		}}
	}}
}}
'''


def sinkronkan(periksa: bool) -> list[str]:
    daftar = pasangan()
    TUJUAN.mkdir(parents=True, exist_ok=True)
    berubah: list[str] = []
    harapan: dict[pathlib.Path, str] = {}
    for berkas, nama, konstruktor, deklarasi, argumen in daftar:
        harapan[TUJUAN / berkas.name] = isi_berkas(nama, konstruktor, deklarasi, argumen)
    harapan[TUJUAN / "r5_surface_test.go"] = isi_test(daftar)

    for jalur, baru in sorted(harapan.items()):
        lama = jalur.read_text() if jalur.exists() else ""
        if lama and PENANDA not in lama:
            continue  # milik manusia
        if lama == baru:
            continue
        berubah.append(str(jalur.relative_to(AKAR)))
        if not periksa:
            jalur.write_text(baru)

    if not periksa:
        tanda = {p.name for p in harapan}
        for jalur in sorted(TUJUAN.glob("*.go")):
            if jalur.name in tanda:
                continue
            if PENANDA in jalur.read_text():
                jalur.unlink()
                berubah.append(f"hapus {jalur.relative_to(AKAR)}")
    return berubah


def main() -> int:
    periksa = "--check" in sys.argv[1:]
    berubah = sinkronkan(periksa)
    if periksa and berubah:
        print("R5 tidak sinkron dengan builder kanon:")
        for jalur in berubah:
            print(f"  {jalur}")
        return 1
    print(f"{len(pasangan())} builder R5; {len(berubah)} berkas diperbarui")
    return 0


if __name__ == "__main__":
    sys.exit(main())
